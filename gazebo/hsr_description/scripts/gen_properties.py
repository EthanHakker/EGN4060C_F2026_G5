#!/usr/bin/env python3
"""Generate urdf/hsr_properties.xacro from docs/cad_mass_properties.json.

Every number written is tagged with its provenance:
  [CAD]       computed by SOLIDWORKS from the approved model geometry and the
              assigned material density (not physically measured).
  [ESTIMATE]  engineering estimate for things the CAD model does not contain.

Conventions
  * Units: SI (m, kg, kg*m^2). Robot frame: X forward, Y left, Z up.
  * SOLIDWORKS reports products of inertia as +integral(x*y dm); URDF expects the
    tensor element -integral(x*y dm). The sign is flipped here.
  * Mounting offsets are the CAD assembly positions (part origin in robot frame).

Usage:  python3 scripts/gen_properties.py   (run from the package root)
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cad = json.load(open(os.path.join(ROOT, "docs", "cad_mass_properties.json")))

# Part origins in the robot frame, from the verified SOLIDWORKS assembly (metres).
MOUNT = {
    "chassis":            (0.0,   0.0, 0.0),
    "lidar_mount":        (0.08,  0.0, 0.185),
    "camera_mast":        (-0.14, 0.0, 0.185),
    "front_sensor_guard": (0.20,  0.0, 0.16),
}

# [ESTIMATE] internal payload (battery, compute, motor drivers) not modelled in CAD.
# The CAD chassis is an empty 3 mm aluminium shell, so without this the robot
# would be unrealistically light (6.7 kg). Set payload_mass to 0 to disable.
PAYLOAD = dict(mass=2.5, size=(0.36, 0.26, 0.06), center=(0.0, 0.0, 0.10))


def tensor(p):
    """URDF-convention inertia tensor about the part CoM, part frame axes."""
    I = p["I_com"]
    return [[I[0], -I[1], -I[2]], [-I[3], I[4], -I[5]], [-I[6], -I[7], I[8]]]


def box_inertia(m, sx, sy, sz):
    return [[m * (sy**2 + sz**2) / 12, 0, 0], [0, m * (sx**2 + sz**2) / 12, 0], [0, 0, m * (sx**2 + sy**2) / 12]]


def merge(items):
    """items: (mass, com_xyz, tensor_about_com). Returns total mass, com, tensor about com."""
    M = sum(m for m, _, _ in items)
    c = [sum(m * r[i] for m, r, _ in items) / M for i in range(3)]
    T = [[0.0] * 3 for _ in range(3)]
    for m, r, I in items:
        d = [r[i] - c[i] for i in range(3)]
        dd = sum(x * x for x in d)
        for i in range(3):
            for j in range(3):
                T[i][j] += I[i][j] + m * ((dd if i == j else 0.0) - d[i] * d[j])
    return M, c, T


def comp(name):
    p = cad[name]
    off = MOUNT.get(name, (0, 0, 0))
    return p["mass"], [off[i] + p["com"][i] for i in range(3)], tensor(p)


base_items = [comp(n) for n in ("chassis", "lidar_mount", "camera_mast", "front_sensor_guard")]
base_cad = merge(base_items)
pay_I = box_inertia(PAYLOAD["mass"], *PAYLOAD["size"])
base_all = merge(base_items + [(PAYLOAD["mass"], list(PAYLOAD["center"]), pay_I)])

lines = ['<?xml version="1.0"?>',
         '<!-- AUTO-GENERATED by scripts/gen_properties.py from docs/cad_mass_properties.json. Do not edit by hand. -->',
         '<!-- [CAD] = computed by SOLIDWORKS from approved geometry + assigned material; [ESTIMATE] = engineering estimate. -->',
         '<robot xmlns:xacro="http://www.ros.org/wiki/xacro">']


def prop(name, value, note):
    lines.append(f'  <xacro:property name="{name}" value="{value:.9g}"/>  <!-- {note} -->')


def inertial_props(prefix, m, c, T, note):
    lines.append(f"  <!-- {prefix}: {note} -->")
    prop(f"{prefix}_mass", m, "kg")
    for i, a in enumerate("xyz"):
        prop(f"{prefix}_com_{a}", c[i], "m, link frame")
    for (i, j), k in {(0, 0): "ixx", (0, 1): "ixy", (0, 2): "ixz", (1, 1): "iyy", (1, 2): "iyz", (2, 2): "izz"}.items():
        prop(f"{prefix}_{k}", T[i][j], "kg*m^2 about CoM")


lines.append("\n  <!-- ===== Inertial properties ===== -->")
inertial_props("base", *base_all,
               f"[CAD] chassis+lidar_mount+camera_mast+guard ({base_cad[0]:.3f} kg) "
               f"+ [ESTIMATE] internal payload {PAYLOAD['mass']} kg box {PAYLOAD['size']} at z={PAYLOAD['center'][2]}")
for link, part in [("wheel", "wheel"), ("lidar", "lidar"), ("pan", "camera_pan_head"),
                   ("camera", "camera"), ("range", "front_range_sensor")]:
    p = cad[part]
    inertial_props(link, p["mass"], p["com"], tensor(p),
                   f"[CAD] {p['part']}, density {p['density']:.0f} kg/m^3. Real sensor mass may differ.")

lines.append("\n  <!-- ===== Geometry and mounting (metres, robot frame) [CAD] ===== -->")
geo = [("wheel_radius", 0.075), ("wheel_width", 0.04), ("wheelbase", 0.25), ("track", 0.36),
       ("chassis_L", 0.40), ("chassis_W", 0.30), ("chassis_H", 0.12), ("ground_clearance", 0.065),
       ("lidar_x", 0.08), ("deck_z", 0.185), ("lidar_standoff", 0.02), ("lidar_radius", 0.0375),
       ("lidar_height", 0.04), ("lidar_scan_offset", 0.02),
       ("mast_x", -0.14), ("mast_height", 0.085), ("mast_radius", 0.01),
       ("pan_radius", 0.025), ("pan_height", 0.025), ("plate_L", 0.05), ("plate_W", 0.07), ("plate_t", 0.005),
       ("camera_D", 0.045), ("camera_W", 0.065), ("camera_H", 0.04), ("camera_lens_x", 0.0275),
       ("range_x", 0.225), ("range_z", 0.16), ("range_tilt_deg", 30.0),
       ("guard_x", 0.20), ("guard_depth", 0.04), ("guard_W", 0.066), ("guard_zmin", -0.02), ("guard_zmax", 0.025)]
for n, v in geo:
    prop(n, v, "[CAD]")

lines.append("\n  <!-- ===== Simulation parameters [ESTIMATE] - tune against real hardware ===== -->")
est = [("wheel_mu1", 1.0, "rubber on concrete/tile, longitudinal"),
       ("wheel_mu2", 0.8, "lateral; slightly lower to ease skid-steer turning"),
       ("wheel_kp", 1.0e6, "contact stiffness N/m"), ("wheel_kd", 100.0, "contact damping N*s/m"),
       ("body_mu", 0.4, "aluminium/plastic on floor"),
       ("wheel_damping", 0.01, "N*m*s/rad joint damping"), ("wheel_friction", 0.0, "N*m joint friction"),
       ("skid_steer_wheel_separation", 0.514,
        "m; DiffDrive EFFECTIVE track (physical 0.36 m x 1.427 slip factor measured vs Gazebo ground truth "
        "by scripts/calibrate_skid_steer.py). Re-run that script after changing mass/friction"),
       ("wheel_effort", 5.0, "N*m per wheel motor"), ("wheel_velocity", 13.3, "rad/s (= 1.0 m/s)"),
       ("pan_lower", -3.14159265, "rad; no cable-wrap limit modelled in CAD"), ("pan_upper", 3.14159265, "rad"),
       ("pan_effort", 1.0, "N*m"), ("pan_velocity", 2.0, "rad/s"), ("pan_damping", 0.05, "N*m*s/rad"),
       ("payload_mass_kg", PAYLOAD["mass"], "already folded into base_* values above")]
for n, v, note in est:
    prop(n, v, f"[ESTIMATE] {note}")

lines.append("</robot>\n")
open(os.path.join(ROOT, "urdf", "hsr_properties.xacro"), "w").write("\n".join(lines))
print(f"base_link: CAD {base_cad[0]:.3f} kg + payload {PAYLOAD['mass']} kg = {base_all[0]:.3f} kg, "
      f"CoM {[round(x, 4) for x in base_all[1]]}")
total = base_all[0] + 4 * cad["wheel"]["mass"] + sum(cad[p]["mass"] for p in ("lidar", "camera_pan_head", "camera", "front_range_sensor"))
print(f"robot total: {total:.3f} kg  (CAD-only {total - PAYLOAD['mass']:.3f} kg)")
